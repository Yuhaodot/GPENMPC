function result=taskIoProvenance()
% Read-only bindings for the exact existing algorithm/frame/protocol helpers.
base=string(gpenmpc_external_path('native_host_package_source'));
build=string(gpenmpc_external_path('host_build_root'));
paths=[fullfile(base,'px4EstimateState.m'); ...
    fullfile(base,'composePhysicalCompensationReferenceNed.m'); ...
    fullfile(build,'host_runtime','+gpenmpcNative','MavlinkSerialLink.m'); ...
    fullfile(build,'host_runtime','+gpenmpcNative','CurrentPhysicalCausalRuntime.m'); ...
    gpenmpc_install_path('rfly','Python38\Lib\site-packages\pymavlink\message_definitions\v1.0\common.xml'); ...
    string(gpenmpc_external_path('px4_odometry_stream_source'))];
hashes=["36E22E2EAB889552A2498A4AF0A3F6AB7B24D2823E23130AEC2D99CED703176A"; ...
    "8D4BE60E2B4DF6056CC7E4C76D9E93A40A10319B1D7B7A4E10E3DF5930103816"; ...
    "0D15FFA88C8CAE73A5EB165529A7997F4AA22782AE3A43119C29689A092644DF"; ...
    "5B493A545682A9B420B1660DA6E568899F35C1AAD9DB27F494424A971EA9369E"; ...
    "12A1327DD4ECBA6398D29D238A39319124AADABACA6FFF3552EBFFDF053E7C6C"; ...
    "4A921A61BED6234C38758C8C33F7026C30854D0621085FA37BFADBAF042E97C5"];
rows=struct('path',{},'bytes',{},'sha256',{});
for k=1:numel(paths)
    info=dir(paths(k));actual=m600check.fileSha256(paths(k));
    assert(isscalar(info)&&~info.isdir&&strcmpi(actual,hashes(k)), ...
        'gpenmpcTaskIo:SourceIdentity','Source dependency changed: %s',paths(k));
    rows(end+1)=struct('path',paths(k),'bytes',info.bytes,'sha256',actual); %#ok<AGROW>
end
names=["gpenmpcNative.px4EstimateState","gpenmpcNative.composePhysicalCompensationReferenceNed", ...
    "gpenmpcNative.MavlinkSerialLink","gpenmpcNative.CurrentPhysicalCausalRuntime"];
for k=1:4
    actual=string(which(names(k)));
    assert(strcmp(actual,paths(k)),'gpenmpcTaskIo:SourceShadow', ...
        'Selected %s is %s; expected %s.',names(k),actual,paths(k));
end
result=struct('source_files',rows,'hardware_actions',0,'claim', ...
    'PURE_HOST_INTERFACE_ENCODING_AND_ATOMIC_DECODING__NOT_LIVE_ADMISSION_OR_DYNAMICS', ...
    'position_reference_semantics','Existing msg84 P/V/A/yaw mask2048; explicit canonical depot translation', ...
    'odometry_semantics','Existing selected EKF2 frame1/child1/estimator8; one packet, original reset counter', ...
    'covariance_delta','Full finite PSD OR exact source diagonal-only pattern; required variances must be finite/nonnegative; documented unknown entries remain NaN, never zero', ...
    'jerk_boundary','Source jerk is retained in host diagnostics; MAVLink msg84 carries P/V/A/yaw.');
end
