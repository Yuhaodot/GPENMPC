classdef RflyLocalTaskCodec
    % Encode RLI1 through MAVLink TUNNEL.
    methods (Static)
        function u=originalNumericalObservation(bound,rls,originalReceiveNs,registered)
            % Provide bootstrap measurements before the first outer command exists,
            % using the same validation as encode.
            s=gpenmpcNative.RflyLocalSnapshotDecoder(rls,originalReceiveNs);key=sourceKey(s);e=registered;
            assert(strcmp(bound.schema,'RFLY_LOCAL_ORIGINAL_INPUT_BINDING_V1') ...
                &&bound.numerical_inputs_complete&&~bound.control_authority ...
                &&isequal(bound.source,key)&&isequal(bound.rotor.source,key) ...
                &&isequal(bound.payload.source,key)&&isequal(bound.wind.source,key) ...
                &&strcmp(bound.rotor.value_kind,'OriginalPlantLagState'), ...
                'gpenmpcNative:LocalTaskSource','Same private source and original lag observation required.');
            assert(isequal(s.identity,e.identity)&&bound.leg_index==e.leg_index ...
                &&isequal(hashBytes(bound.payload.task_sha256),hashBytes(e.task_sha256)) ...
                &&strcmpi(e.configuration_sha256,'A859433D0AA774013341444A4B9AE971A34F12B4FB89C0A004B2CB3E013FCEBA'), ...
                'gpenmpcNative:LocalTaskIdentity','Registered current method/task/leg required.');
            r=bound.rotor.original_observation;
            assert(r.original_board_ingress_us==s.original_receipt_us&&r.dll_generation>0&&r.dll_session>0 ...
                &&r.original_host_receive_ns>0&&isfinite(r.original_sim_time_s)&&r.original_sim_time_s>=0 ...
                &&all(isfinite(r.observed_thrust_n))&&all(r.observed_thrust_n>=0) ...
                &&bound.payload.original_schedule_generation>0&&isfinite(bound.payload.payload_kg)&&bound.payload.payload_kg>=0 ...
                &&bound.wind.original_estimate_generation>0&&all(isfinite(bound.wind.estimate_xy_mps)), ...
                'gpenmpcNative:LocalTaskIngress','Original numeric observation and source time required.');
            for h={r.original_observation_sha,bound.rotor.verified_association_receipt_sha256, ...
                    bound.payload.original_schedule_evidence_sha256,bound.wind.original_estimate_evidence_sha256}
                hashBytes(h{1});
            end
            u=struct('source',key,'original_sensor52',s.original_sensor52,'leg_index',bound.leg_index, ...
                'execution_session_sha256',hashBytes(e.execution_session_sha256),'task_sha256',hashBytes(e.task_sha256), ...
                'configuration_sha256',hashBytes(e.configuration_sha256),'reference_asset_sha256',hashBytes(e.reference_asset_sha256), ...
                'rotor',bound.rotor,'payload',bound.payload,'wind',bound.wind,'outer',[], ...
                'control_authority',false,'outer_command_fabricated',false);
        end
        function bytes=encode(bound,rls,originalReceiveNs,outer,registered)
            gpenmpcNative.RflyLocalTaskCodec.originalNumericalObservation(bound,rls,originalReceiveNs,registered);
            s=gpenmpcNative.RflyLocalSnapshotDecoder(rls,originalReceiveNs);
            key=sourceKey(s);e=registered;
            assert(strcmp(bound.schema,'RFLY_LOCAL_ORIGINAL_INPUT_BINDING_V1') ...
                &&bound.numerical_inputs_complete&&~bound.control_authority ...
                &&isequal(bound.source,key)&&isequal(bound.rotor.source,key) ...
                &&isequal(bound.payload.source,key)&&isequal(bound.wind.source,key) ...
                &&strcmp(bound.rotor.value_kind,'OriginalPlantLagState'), ...
                'gpenmpcNative:LocalTaskSource','Same private source and original lag observation required.');
            assert(isequal(s.identity,e.identity)&&bound.leg_index==e.leg_index ...
                &&isequal(hashBytes(bound.payload.task_sha256),hashBytes(e.task_sha256)) ...
                &&strcmpi(e.configuration_sha256,'A859433D0AA774013341444A4B9AE971A34F12B4FB89C0A004B2CB3E013FCEBA'), ...
                'gpenmpcNative:LocalTaskIdentity','Registered current method/task/leg required.');
            r=bound.rotor.original_observation;
            assert(r.original_board_ingress_us==s.original_receipt_us, ...
                'gpenmpcNative:LocalTaskIngress','Original source receive time cannot be renewed.');
            bytes=[uint8('RLI1').';hashBytes(e.execution_session_sha256);hashBytes(e.configuration_sha256); ...
                hashBytes(e.task_sha256);hashBytes(e.reference_asset_sha256);be(uint32(e.leg_index)); ...
                be(s.identity.uid);be(s.identity.boot_generation);uint8(s.identity.system);uint8(s.identity.component); ...
                be(key.sample_us);be(key.publication_us);be(key.original_receipt_us);be(key.source_generation); ...
                be(key.generation_delta);be(key.sample_delta_us);uint8(key.reset_counter);hashBytes(key.state_and_origin_sha256); ...
                s.original_sensor52;be(r.dll_generation);be(r.dll_session);be(r.original_host_receive_ns); ...
                be(double(r.original_sim_time_s));be(double(r.observed_thrust_n(:)));hashBytes(r.original_observation_sha); ...
                hashBytes(bound.rotor.verified_association_receipt_sha256); ...
                be(bound.payload.original_schedule_generation);hashBytes(bound.payload.original_schedule_evidence_sha256);be(double(bound.payload.payload_kg)); ...
                be(bound.wind.original_estimate_generation);hashBytes(bound.wind.original_estimate_evidence_sha256);be(double(bound.wind.estimate_xy_mps(:))); ...
