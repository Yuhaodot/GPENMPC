        function [ok,reason,context] = validateRuntime(obj,runtime,nowNs)
            ok=false; reason="MALFORMED_PHYSICAL_CAUSAL_RUNTIME"; context=struct();
            required={'schema','task_identity_sha256','plant_truth_used', ...
                'virtual_actuator','wind','task'};
            if ~isstruct(runtime) || ~isscalar(runtime) ...
                    || ~all(isfield(runtime,required)) ...
                    || string(runtime.schema) ...
                        ~= "GPENMPC_PHYSICAL_CAUSAL_RUNTIME_INPUT_V1" ...
                    || ~obj.isSha256(runtime.task_identity_sha256) ...
                    || ~strcmpi(string(runtime.task_identity_sha256), ...
                        obj.TaskIdentitySha256) ...
                    || ~(islogical(runtime.plant_truth_used) ...
                        && isscalar(runtime.plant_truth_used) ...
                        && ~runtime.plant_truth_used)
                reason="RUNTIME_IDENTITY_OR_TRUTH_ISOLATION_REJECTED"; return
            end
            actuator=runtime.virtual_actuator; wind=runtime.wind; task=runtime.task;
            if ~obj.validStamp(actuator, ...
                    "HOST_M600_VIRTUAL_ACTUATOR_INTERFACE",nowNs) ...
                    || ~obj.validStamp(wind,"FROZEN_TASK_WIND_ESTIMATOR",nowNs)
                reason="STALE_OR_INVALID_RUNTIME_SOURCE"; return
            end
            actuatorFields={'ordering','rotor_thrust_state_n'};
            windFields={'estimate_xy_mps'};
            taskFields={'source','payload_kg','leg_index'};
            if ~all(isfield(actuator,actuatorFields)) ...
                    || string(actuator.ordering)~="SOFTWARE_M600_ORDER" ...
                    || ~all(isfield(wind,windFields)) ...
                    || ~all(isfield(task,taskFields)) ...
                    || string(task.source)~="FROZEN_GPENMPC_TASK_STATE" ...
                    || ~obj.finiteVector(actuator.rotor_thrust_state_n,6) ...
                    || any(actuator.rotor_thrust_state_n(:)<0) ...
                    || any(actuator.rotor_thrust_state_n(:)> ...
                        obj.Assets.kernelParameters.rotorUpper+1.0e-12) ...
                    || ~obj.finiteVector(wind.estimate_xy_mps,2) ...
                    || ~obj.finiteScalar(task.payload_kg) || task.payload_kg<0 ...
                    || ~obj.finiteInteger(task.leg_index) || task.leg_index<1
                reason="NONFINITE_OR_OUT_OF_DOMAIN_RUNTIME_VALUE"; return
            end
            actuatorGeneration=double(actuator.generation);
            windGeneration=double(wind.generation);
            if actuatorGeneration<=obj.LastVirtualActuatorGeneration ...
                    || windGeneration<obj.LastWindGeneration
                reason="NONADVANCING_OR_REVERSED_RUNTIME_GENERATION"; return
            end
            context=struct( ...
                'rotor_thrust_state_n',double(actuator.rotor_thrust_state_n(:)), ...
                'wind_estimate_xy_mps',double(wind.estimate_xy_mps(:)), ...
                'payload_kg',double(task.payload_kg), ...
                'leg_index',double(task.leg_index), ...
                'virtual_actuator_generation',actuatorGeneration, ...
                'wind_generation',windGeneration);
            ok=true; reason="PASS";
        end

