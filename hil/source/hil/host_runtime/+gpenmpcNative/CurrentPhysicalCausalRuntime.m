        function ok = validStamp(obj,value,source,nowNs)
            required={'source','rx_ns','generation','valid'};
            ok=isstruct(value)&&isscalar(value)&&all(isfield(value,required)) ...
                && string(value.source)==source ...
                && islogical(value.valid)&&isscalar(value.valid)&&value.valid ...
                && obj.finiteInteger(value.generation)&&value.generation>=1 ...
                && obj.finiteScalar(value.rx_ns)&&value.rx_ns>=0 ...
                && value.rx_ns<=nowNs ...
                && nowNs-value.rx_ns<=obj.Expected.maximum_runtime_age_ns;
        end

        function ok = validReference(obj,value)
            required={'position_m','velocity_mps','acceleration_mps2','jerk_mps3'};
            ok=isstruct(value)&&isscalar(value)&&all(isfield(value,required));
            if ~ok, return, end
            for k=1:numel(required)
                if ~obj.finiteVector(value.(required{k}),3), ok=false; return, end
            end
        end

