        function response = commitFailure(obj,generation,reason,hardInvalid,boundary,wallS)
            decision = struct('method',string(obj.Config.method), ...
                'success',false,'hard_invalid',logical(hardInvalid), ...
                'phase_acceleration_s_inv',0.0, ...
                'outer_acceleration_correction_f_mps2',zeros(3,1), ...
                'fallback_reason',string(reason),'elapsed_seconds',double(wallS), ...
                'gp_b1_fallback_active',false);
            audit = struct('current_hard_invalid',logical(hardInvalid), ...
                'coordinated_selected_method',string(obj.Config.method));
            [obj.Adapter,event] = gpenmpcNative.commitBoardReferenceDecision( ...
                obj.Adapter,decision,audit,uint64(generation),obj.Config);
            obj.LastGeneration = uint64(generation);
            if hardInvalid
                obj.Failed = true;
                obj.FailureCode = string(reason);
            end
            response = obj.responseStruct(generation,boundary,event, ...
                decision,audit,wallS,"FAILURE_CONTINUITY_COMMIT");
        end

