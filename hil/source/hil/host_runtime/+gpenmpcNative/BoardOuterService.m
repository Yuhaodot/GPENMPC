    methods
        function obj = BoardOuterService(workRoot,expected,trajectory)
            % A new execution session after ground service may start at a later mission leg.
            if isfield(expected,'initial_leg_index')
                v=expected.initial_leg_index;
                assert(isnumeric(v)&&isreal(v)&&isscalar(v)&&isfinite(v) ...
                    &&v>=1&&v==fix(v)&&v<=double(intmax('int32')), ...
                    'gpenmpcNative:CanonicalInitialLeg','Explicit positive global task leg required.');
                obj.CurrentLegIndex=double(v);
            end
            assert(isfield(expected,'canonical_package_root'), ...
                'gpenmpcNative:CanonicalPackageRequired', ...
                'The service must explicitly bind the canonical assets in this distribution.');
            assets = gpenmpcNative.loadCanonicalAssets( ...
                string(expected.canonical_package_root));
            obj.Assets = assets;
            assert(isfield(expected,'initial_payload_kg') ...
                &&isnumeric(expected.initial_payload_kg)&&isscalar(expected.initial_payload_kg) ...
                &&isfinite(expected.initial_payload_kg)&&expected.initial_payload_kg>=0, ...
                'gpenmpcNative:CanonicalInitialPayload','Explicit task initial payload required.');
            obj.CurrentPayloadKg=double(expected.initial_payload_kg);
            obj.WorkRoot = string(workRoot);
            obj.Expected = expected;
            obj.Config = assets.enmpc;
            obj.ConfigurationPayloadSha256 = ...
                string(assets.configurationBinding.effective_configuration_payload_sha256);
            obj.Trajectory = trajectory;
            obj.Adapter = gpenmpcNative.initializeBoardReferenceAdapter( ...
                obj.Config,trajectory,string(obj.Config.method));
            assert(isfield(expected,'task_identity_sha256'), ...
                'gpenmpcNative:BoardOuterTaskIdentity', ...
                'The frozen task identity is required.');
            obj.PhysicalRuntime = gpenmpcNative.CurrentPhysicalCausalRuntime( ...
                workRoot,expected,string(expected.task_identity_sha256),assets);
            obj.WarmStart = zeros(1,obj.Config.decision_dimension);
            obj.AsyncEnabled=isfield(expected,'async_outer_required') ...
                && islogical(expected.async_outer_required) ...
                && isscalar(expected.async_outer_required) ...
                && expected.async_outer_required;
            if obj.AsyncEnabled
                bindingPath=assets.binding_path;
                fixed=struct('source_root',assets.sourceRoot, ...
                    'config',assets.enmpc,'context',assets.prediction_context, ...
                    'gp_model',assets.gp_model, ...
                    'source_manifest_sha256', ...
                        string(assets.binding.source_manifest_sha256), ...
                    'source_binding_sha256',gpenmpcNative.fileSha256(bindingPath), ...
                    'configuration_payload_sha256', ...
                        string(assets.configurationBinding.effective_configuration_payload_sha256), ...
                    'gp_model_sha256',gpenmpcNative.fileSha256(assets.gpModelPath));
                obj.FixedAssets=parallel.pool.Constant(fixed);
                obj.Worker=gpenmpcNative.OuterMailboxWorker( ...
                    obj.FixedAssets,obj.Config.solver_deadline_s);
            end
        end

        function receipt = prepare(obj,nowNs,px4Sample,runtime)
            % Pre-formal JIT/content rehearsal. It consumes no generation,
            % commits no command, and cannot publish a board reference.
            assert(~obj.Failed && obj.LastGeneration==0 && ~obj.Prepared && ~obj.PreparationInFlight, ...
                'gpenmpcNative:BoardOuterPreparationState', ...
                'Preparation is permitted exactly once before generation 1.');
            obj.requireRuntimeTask(runtime);
            phase = struct('progress_s',obj.Adapter.phase_s, ...
                'progress_rate',obj.Adapter.phase_rate, ...
                'previous_phase_acceleration_s_inv', ...
                    obj.Adapter.previous_phase_acceleration_s_inv);
            [snapshot,accepted,reason,boundary] = ...
                gpenmpcNative.makeBoardOuterSnapshot(obj.WorkRoot, ...
                    px4Sample,obj.snapshotExpected(),nowNs,runtime,obj.Trajectory, ...
                    phase,obj.WarmStart,obj.Assets);
            if ~accepted
                obj.Failed=true;obj.FailureCode=string(reason);
                receipt=struct('status','FAIL_CLOSED','reason',string(reason), ...
                    'input_boundary',boundary,'generation_consumed',false, ...
                    'command_committed',false,'hardware_actions',0);
                return
            end
            started=tic;
            probe=gpenmpcNative.solveCurrentOuter(snapshot);
            obj.PreparationWallS=toc(started);
            obj.PreparationCalls=obj.PreparationCalls+uint64(1);
            assert(probe.used_current_supervisor ...
                && probe.snapshot_timestamp_ns==snapshot.snapshot_timestamp_ns, ...
                'gpenmpcNative:BoardOuterPreparationBinding', ...
                'Preparation result is not bound to the rehearsal snapshot.');
            obj.Prepared=true;
            obj.LastInputGenerations=obj.boundaryGenerations(boundary);
            obj.LastInputBoundary=boundary;
            if obj.AsyncEnabled
                warmTimer=tic;
                compact=obj.compactSnapshot(snapshot);
                assert(obj.Worker.submit(compact,0,double(nowNs)), ...
                    'gpenmpcNative:BoardOuterAsyncWarmSubmit', ...
                    'Unable to submit the pre-formal async warm-up.');
                ready=false;reason='PENDING';warmResult=struct();
                while ~ready && toc(warmTimer)<60.0
                    [ready,warmResult,reason]=obj.Worker.poll( ...
                        double(nowNs),0);
                    if reason=="WORKER_ERROR_NO_COMMAND",break,end
                    if ~ready,pause(0.002);end
                end
                obj.AsyncWarmupWallS=toc(warmTimer);
                assert(ready && reason=="FRESH_RESULT" ...
                    && logical(warmResult.dynamic_snapshot_only) ...
                    && logical(warmResult.immutable_worker_constant), ...
                    'gpenmpcNative:BoardOuterAsyncWarmup', ...
                    'Async solver warm-up failed before formal t0: %s',reason);
            end
            receipt=struct('status','PASS_HOST_PREPARATION', ...
                'wall_s',obj.PreparationWallS, ...
                'solver_deadline_s',obj.Config.solver_deadline_s, ...
                'generation_consumed',false,'command_committed',false, ...
                'publication_count',0,'input_boundary',boundary, ...
                'async_enabled',obj.AsyncEnabled, ...
                'async_warmup_wall_s',obj.AsyncWarmupWallS, ...
                'preparation_decision',probe.decision, ...
                'preparation_audit',probe.audit, ...
                'hardware_actions',0,'com_open',0,'board_access',0);
        end

        function receipt=beginPreparation(obj,nowNs,px4Sample,runtime)
            % The SAME persistent worker performs the only actual-snapshot
            % preparation probe. No main-thread duplicate solver call, wait,
            % generation-1 result, warm-start commit or observer update.
            assert(~obj.Failed&&~obj.Prepared&&~obj.PreparationInFlight ...
                &&obj.LastGeneration==0&&obj.PreparationCalls==0&&obj.AsyncEnabled, ...
                'gpenmpcNative:BoardOuterPreparationState','One async preparation before formal generation 1 required.');
            assert(isa(nowNs,'uint64')&&isscalar(nowNs)&&nowNs>0, ...
                'gpenmpcNative:BoardOuterPreparationTime','Original HOST event required.');
            obj.requireRuntimeTask(runtime);
            phase=struct('progress_s',obj.Adapter.phase_s,'progress_rate',obj.Adapter.phase_rate, ...
                'previous_phase_acceleration_s_inv',obj.Adapter.previous_phase_acceleration_s_inv);
            [snapshot,accepted,reason,boundary]=gpenmpcNative.makeBoardOuterSnapshot( ...
                obj.WorkRoot,px4Sample,obj.snapshotExpected(),nowNs,runtime,obj.Trajectory, ...
                phase,obj.WarmStart,obj.Assets);
            if ~accepted
                obj.Failed=true;obj.FailureCode=string(reason);
                receipt=struct('status','FAIL_CLOSED','reason',string(reason), ...
                    'input_boundary',boundary,'generation_consumed',false, ...
                    'command_committed',false,'hardware_actions',0);return
            end
            obj.PreparationWorkerExpiryBaseline=obj.Worker.Expired;
            obj.PreparationNumericalState=struct('warm_start',obj.WarmStart, ...
                'adapter',obj.Adapter,'physical',obj.PhysicalRuntime.status());
            assert(obj.Worker.submit(obj.compactSnapshot(snapshot),0,double(nowNs)), ...
                'gpenmpcNative:BoardOuterAsyncWarmSubmit','The sole worker must accept generation-0 preparation.');
            obj.PreparationCalls=obj.PreparationCalls+uint64(1);
            obj.PreparationInFlight=true;obj.PreparationBoundary=boundary;
            obj.PreparationSnapshotNs=uint64(snapshot.snapshot_timestamp_ns);
            obj.PreparationSubmittedNs=nowNs;obj.PreparationLastEventNs=nowNs;
            obj.PreparationResultTiming="PENDING";
            receipt=obj.preparationReceipt('PREPARATION_SUBMITTED','PENDING');
        end

        function receipt=pollPreparation(obj,nowNs)
            assert(~obj.Failed&&~obj.Prepared&&obj.PreparationInFlight, ...
                'gpenmpcNative:BoardOuterPreparationState','No current preparation request.');
            assert(isa(nowNs,'uint64')&&isscalar(nowNs)&&nowNs>=obj.PreparationLastEventNs, ...
                'gpenmpcNative:BoardOuterPreparationTime','Preparation HOST event regressed.');
            obj.PreparationLastEventNs=nowNs;
            [ready,probe,reason]=obj.Worker.poll(double(nowNs),0);
            obj.PreparationWallS=double(nowNs-obj.PreparationSubmittedNs)*1e-9;
            obj.AsyncWarmupWallS=obj.PreparationWallS;
            obj.PreparationExpired=obj.Worker.Expired>obj.PreparationWorkerExpiryBaseline;
            % Pass current time to the worker to preserve its .28 s expiry ledger.
            % The 60 s cold-preparation ceiling is separate from task deadlines.
            if obj.PreparationWallS>=60.0||string(reason)=="WORKER_ERROR_NO_COMMAND"
                obj.PreparationInFlight=false;obj.Failed=true;
                obj.FailureCode="PREPARATION__"+string(reason);
                if obj.PreparationWallS>=60.0,obj.FailureCode="PREPARATION_COLD_LIMIT_EXPIRED";end
                receipt=obj.preparationReceipt('FAIL_CLOSED',obj.FailureCode);return
            end
            late=string(reason)=="LATE_RESULT_DISCARDED";
            if ~ready&&~late
                assert(any(string(reason)==["PENDING","EXPIRED_STILL_BUSY_NO_REQUEUE"]), ...
                    'gpenmpcNative:BoardOuterPreparationWorker','Unexpected preparation disposition.');
                receipt=obj.preparationReceipt('PREPARATION_PENDING',reason);return
            end
            if late
                % Retain an expired gen-0 rehearsal result as diagnostics only.
                probe=obj.Worker.LastCompletedDiagnostic;
                obj.PreparationResultTiming="COLD_REHEARSAL_COMPLETED_EXPIRED";
            else
                obj.PreparationResultTiming="DIAGNOSTIC_WITHIN_SOLVER_DEADLINE";
            end
            assert(probe.used_current_supervisor ...
                &&uint64(probe.snapshot_timestamp_ns)==obj.PreparationSnapshotNs ...
                &&string(probe.configuration_payload_sha256)==obj.ConfigurationPayloadSha256 ...
                &&logical(probe.dynamic_snapshot_only)&&logical(probe.immutable_worker_constant), ...
                'gpenmpcNative:BoardOuterPreparationBinding','Actual same-input preparation result required.');
            assert(isequaln(obj.PreparationNumericalState,struct('warm_start',obj.WarmStart, ...
                'adapter',obj.Adapter,'physical',obj.PhysicalRuntime.status())), ...
                'gpenmpcNative:BoardOuterPreparationMutation','Preparation must not mutate numerical state.');
            obj.Prepared=true;obj.PreparationInFlight=false;
            obj.LastInputGenerations=obj.boundaryGenerations(obj.PreparationBoundary);
            obj.LastInputBoundary=obj.PreparationBoundary;
            receipt=obj.preparationReceipt('PASS_HOST_PREPARATION',reason);
            receipt.preparation_decision=probe.decision;receipt.preparation_audit=probe.audit;
            receipt.numerical_state_unchanged=true;
        end

        function response = update(obj,generation,nowNs,px4Sample,runtime)
            obj.requireActiveGeneration(generation);
            assert(~obj.AsyncInFlight,'gpenmpcNative:BoardOuterAsyncBusy', ...
                'A synchronous solve cannot compete with the in-flight worker.');
            obj.requireRuntimeTask(runtime);
            phase = struct('progress_s',obj.Adapter.phase_s, ...
                'progress_rate',obj.Adapter.phase_rate, ...
                'previous_phase_acceleration_s_inv', ...
                    obj.Adapter.previous_phase_acceleration_s_inv);
            [snapshot,accepted,reason,boundary] = ...
                gpenmpcNative.makeBoardOuterSnapshot(obj.WorkRoot, ...
                    px4Sample,obj.snapshotExpected(),nowNs,runtime,obj.Trajectory, ...
                    phase,obj.WarmStart,obj.Assets);
            if ~accepted
                obj.RejectedSnapshots = obj.RejectedSnapshots + uint64(1);
                response = obj.commitFailure(generation,reason,true,boundary,0.0);
                return
            end
            inputGenerations=obj.boundaryGenerations(boundary);
            [advanced,advanceReason]=gpenmpcNative.validateOuterObservationAdvance( ...
                obj.LastInputBoundary,boundary);
            if ~advanced
                obj.RejectedSnapshots=obj.RejectedSnapshots+uint64(1);
                boundary.status="REJECTED";
                boundary.reason=advanceReason;
                response=obj.commitFailure(generation, ...
                    advanceReason,true,boundary,0.0);
                return
            end
            obj.LastInputGenerations=inputGenerations;
            obj.LastInputBoundary=boundary;
            started = tic;
            result = gpenmpcNative.solveCurrentOuter(snapshot);
            wallS = toc(started);
            assert(result.snapshot_timestamp_ns == snapshot.snapshot_timestamp_ns ...
                && string(result.configuration_payload_sha256) == ...
                    string(snapshot.configuration_payload_sha256), ...
                'gpenmpcNative:BoardOuterResultBinding', ...
                'Current solver result is not bound to the submitted snapshot.');
            if wallS > obj.Config.solver_deadline_s
                obj.ExpiredSolverResults = obj.ExpiredSolverResults + uint64(1);
                response = obj.commitFailure(generation, ...
                    "SOLVER_WALL_DEADLINE_EXCEEDED",false,boundary,wallS);
                return
            end
            [obj.Adapter,event] = gpenmpcNative.commitBoardReferenceDecision( ...
                obj.Adapter,result.decision,result.audit,uint64(generation),obj.Config);
            obj.WarmStart = result.warm_start;
            obj.LastGeneration = uint64(generation);
            obj.AcceptedSolverResults = obj.AcceptedSolverResults + uint64(1);
            obj.FreshOuterForCurrentLeg=~obj.Adapter.hard_invalid_latched;
            if obj.Adapter.hard_invalid_latched
                obj.Failed = true;
                obj.FailureCode = "SOLVER_HARD_INVALID";
            end
            response = obj.responseStruct(generation,boundary,event, ...
                result.decision,result.audit,wallS,"FRESH_SOLVER_RESULT");
        end

        function response = submitUpdate(obj,generation,nowNs,px4Sample,runtime)
            % Submit one outer update asynchronously; permit one in-flight request
            % and account for rejected snapshots through continuity handling.
            assert(obj.AsyncEnabled && ~isempty(obj.Worker), ...
                'gpenmpcNative:BoardOuterAsyncNotEnabled', ...
                'The explicit async_outer_required identity is absent.');
            obj.requireActiveGeneration(generation);
            assert(~obj.AsyncInFlight, ...
                'gpenmpcNative:BoardOuterAsyncBusy', ...
                'Only one outer solver request may be in flight.');
            obj.requireRuntimeTask(runtime);
            phase = struct('progress_s',obj.Adapter.phase_s, ...
                'progress_rate',obj.Adapter.phase_rate, ...
                'previous_phase_acceleration_s_inv', ...
                    obj.Adapter.previous_phase_acceleration_s_inv);
            [snapshot,accepted,reason,boundary] = ...
                gpenmpcNative.makeBoardOuterSnapshot(obj.WorkRoot, ...
                    px4Sample,obj.snapshotExpected(),nowNs,runtime,obj.Trajectory, ...
                    phase,obj.WarmStart,obj.Assets);
            if ~accepted
                obj.RejectedSnapshots=obj.RejectedSnapshots+uint64(1);
                response=obj.commitFailure(generation,reason,true,boundary,0.0);
                response.async_disposition="REJECTED_BEFORE_SUBMIT";
                return
            end
            inputGenerations=obj.boundaryGenerations(boundary);
            [advanced,advanceReason]=gpenmpcNative.validateOuterObservationAdvance( ...
                obj.LastInputBoundary,boundary);
            if ~advanced
                obj.RejectedSnapshots=obj.RejectedSnapshots+uint64(1);
                boundary.status="REJECTED";
                boundary.reason=advanceReason;
                response=obj.commitFailure(generation, ...
                    advanceReason,true,boundary,0.0);
                response.async_disposition="REJECTED_BEFORE_SUBMIT";
                return
            end
            compact=obj.compactSnapshot(snapshot);
            submitted=obj.Worker.submit(compact,double(generation),double(nowNs));
            assert(submitted,'gpenmpcNative:BoardOuterAsyncSubmit', ...
                'The single-flight outer solver rejected an idle submit.');
            obj.AsyncInFlight=true;
            obj.AsyncCommitted=false;
            obj.AsyncRetiredForLifecycle=false;
            obj.AsyncGeneration=uint64(generation);
            obj.AsyncSubmittedNs=uint64(nowNs);
            obj.AsyncBoundary=boundary;
            obj.AsyncSnapshotTimestampNs=uint64(snapshot.snapshot_timestamp_ns);
            obj.AsyncInputGenerations=inputGenerations;
            obj.AsyncSubmitted=obj.AsyncSubmitted+uint64(1);
            response=struct('schema', ...
                'GPENMPC_BOARD_OUTER_ASYNC_SUBMIT_RESPONSE_V1', ...
                'status','SUBMITTED','generation',double(generation), ...
                'snapshot_timestamp_ns',double(snapshot.snapshot_timestamp_ns), ...
                'input_boundary',boundary,'hardware_actions',0, ...
                'com_open',0,'board_access',0);
        end

        function response = pollUpdate(obj,nowNs)
            % Poll the one in-flight solver without blocking. Deadline
            % expiry commits the existing safe-continuity fallback exactly
            % once; a later worker result is retained only as a discard fact.
            assert(isfinite(nowNs)&&nowNs>=0&&nowNs==fix(nowNs), ...
                'gpenmpcNative:BoardOuterAsyncPollTime','Invalid poll time.');
            if ~obj.AsyncInFlight
                response=struct('schema', ...
                    'GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                    'status','IDLE','hardware_actions',0, ...
                    'com_open',0,'board_access',0);
                return
            end
            if obj.AsyncRetiredForLifecycle
                % Drain the worker without applying results across LAND or leg transitions.
                [~,~,retiredReason]=obj.Worker.poll(double(nowNs),-1);
                terminal=any(string(retiredReason)==["STALE_GENERATION_DISCARDED", ...
                    "LATE_RESULT_DISCARDED","WORKER_ERROR_NO_COMMAND"]);
                if terminal
                    obj.AsyncInFlight=false;
                    obj.AsyncLifecycleDiscarded=obj.AsyncLifecycleDiscarded+uint64(1);
                    if string(retiredReason)=="WORKER_ERROR_NO_COMMAND"
                        obj.Failed=true;obj.FailureCode="RETIRED_OUTER_WORKER_ERROR";
                    end
                end
                response=struct('schema','GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                    'status','LIFECYCLE_RETIRED_RESULT_DRAIN','terminal',terminal, ...
                    'worker_reason',string(retiredReason),'generation',double(obj.AsyncGeneration), ...
                    'command_committed',false,'publication_allowed',false, ...
                    'hardware_actions',0,'com_open',0,'board_access',0);
                return
            end
            [ready,result,reason]=obj.Worker.poll( ...
                double(nowNs),double(obj.AsyncGeneration));
            elapsedS=max(0,(double(nowNs)-double(obj.AsyncSubmittedNs))*1e-9);
            if ready && ~obj.AsyncCommitted
                assert(uint64(result.snapshot_timestamp_ns)== ...
                    obj.AsyncSnapshotTimestampNs ...
                    && string(result.configuration_payload_sha256)== ...
                    obj.ConfigurationPayloadSha256 ...
                    && logical(result.dynamic_snapshot_only) ...
                    && logical(result.immutable_worker_constant), ...
                    'gpenmpcNative:BoardOuterAsyncBinding', ...
                    'Async solver result is not bound to the submitted identity.');
                [obj.Adapter,event]=gpenmpcNative.commitBoardReferenceDecision( ...
                    obj.Adapter,result.decision,result.audit, ...
                    obj.AsyncGeneration,obj.Config);
                obj.WarmStart=result.warm_start;
                obj.LastGeneration=obj.AsyncGeneration;
                obj.LastInputGenerations=obj.AsyncInputGenerations;
                obj.LastInputBoundary=obj.AsyncBoundary;
                obj.AcceptedSolverResults=obj.AcceptedSolverResults+uint64(1);
                obj.AsyncAccepted=obj.AsyncAccepted+uint64(1);
                obj.FreshOuterForCurrentLeg=~obj.Adapter.hard_invalid_latched;
                if obj.Adapter.hard_invalid_latched
                    obj.Failed=true;obj.FailureCode="SOLVER_HARD_INVALID";
                end
                response=obj.responseStruct(obj.AsyncGeneration, ...
                    obj.AsyncBoundary,event,result.decision,result.audit, ...
                    elapsedS,"FRESH_ASYNC_SOLVER_RESULT");
                response.schema= ...
                    "GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1";
                response.status="FRESH_RESULT_COMMITTED";
                obj.AsyncCommitted=true;
                obj.AsyncInFlight=false;
                return
            end
            if obj.AsyncCommitted
                if reason=="WORKER_ERROR_NO_COMMAND"
                    % After deadline fallback consumes a generation, a later worker error
                    % must end the drain and clear the pending job.
                    obj.AsyncInFlight=false;
                    obj.Failed=true;obj.FailureCode="EXPIRED_OUTER_WORKER_ERROR";
                    obj.Adapter.hard_invalid_latched=true;
                    obj.Adapter.publication_allowed=false;
                    response=struct('schema', ...
                        'GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                        'status','FAIL_CLOSED_EXPIRED_WORKER_ERROR', ...
                        'generation',double(obj.AsyncGeneration), ...
                        'additional_command_committed',false, ...
                        'hardware_actions',0,'com_open',0,'board_access',0);
                elseif reason=="LATE_RESULT_DISCARDED" ...
                        || reason=="STALE_GENERATION_DISCARDED"
                    obj.AsyncLateDiscarded=obj.AsyncLateDiscarded+uint64(1);
                    obj.AsyncInFlight=false;
                    response=struct('schema', ...
                        'GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                        'status',string(reason),'generation', ...
                        double(obj.AsyncGeneration),'hardware_actions',0, ...
                        'com_open',0,'board_access',0);
                else
                    response=struct('schema', ...
                        'GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                        'status','EXPIRED_WORKER_DRAIN_PENDING', ...
                        'generation',double(obj.AsyncGeneration), ...
                        'hardware_actions',0,'com_open',0,'board_access',0);
                end
                return
            end
            if reason=="WORKER_ERROR_NO_COMMAND"
                response=obj.commitFailure(obj.AsyncGeneration, ...
                    "ASYNC_OUTER_WORKER_ERROR",true,obj.AsyncBoundary,elapsedS);
                response.schema= ...
                    "GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1";
                response.status="FAIL_CLOSED_WORKER_ERROR";
                obj.AsyncCommitted=true;
                obj.AsyncInFlight=false;
                return
            end
            if elapsedS>obj.Config.solver_deadline_s
                obj.ExpiredSolverResults=obj.ExpiredSolverResults+uint64(1);
                obj.AsyncExpired=obj.AsyncExpired+uint64(1);
                response=obj.commitFailure(obj.AsyncGeneration, ...
                    "SOLVER_WALL_DEADLINE_EXCEEDED",false, ...
                    obj.AsyncBoundary,elapsedS);
                response.schema= ...
                    "GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1";
                response.status="DEADLINE_FALLBACK_COMMITTED";
                obj.LastInputGenerations=obj.AsyncInputGenerations;
                obj.LastInputBoundary=obj.AsyncBoundary;
                obj.AsyncCommitted=true;
                return
            end
            response=struct('schema', ...
                'GPENMPC_BOARD_OUTER_ASYNC_POLL_RESPONSE_V1', ...
                'status','PENDING','generation',double(obj.AsyncGeneration), ...
                'elapsed_s',elapsedS,'hardware_actions',0, ...
                'com_open',0,'board_access',0);
        end

        function response = expire(obj,generation,reason)
            obj.requireActiveGeneration(generation);
            assert(~obj.AsyncInFlight,'gpenmpcNative:BoardOuterAsyncBusy', ...
                'The in-flight request is accounted only by pollUpdate.');
            obj.ExpiredSolverResults = obj.ExpiredSolverResults + uint64(1);
            boundary = struct('status',"NOT_SUBMITTED", ...
                'reason',string(reason),'hardware_actions',0);
            response = obj.commitFailure(generation,string(reason),false, ...
                boundary,obj.Config.solver_deadline_s);
        end

        function receipt = suspendOuterForLifecycle(obj,reason,nowNs)
            % Suspend after the last control sample and before LAND.
            % Drain an executing solver without reusing its result on the next leg.
            physical=obj.PhysicalRuntime.status();
            assert(~physical.sample_open, ...
                'gpenmpcNative:LifecycleOpenControlSample', ...
                'Close the last physical sample before lifecycle suspension.');
            assert(isscalar(nowNs)&&isfinite(nowNs)&&nowNs>=0 ...
                &&isscalar(string(reason)) ...
                &&any(string(reason)==["NATIVE_LAND","GROUND_SERVICE","SAFETY_EXIT"]), ...
                'gpenmpcNative:LifecycleSuspensionInput','Invalid lifecycle event.');
            wasSuspended=obj.OuterSuspended;
            obj.OuterSuspended=true;
            obj.Adapter.publication_allowed=false;
            if ~wasSuspended
                obj.LifecycleSuspendCount=obj.LifecycleSuspendCount+uint64(1);
            end
            if obj.AsyncInFlight
                obj.AsyncRetiredForLifecycle=true;
                % Keep submitted work accounted during landing without treating it as an accepted solve.
                obj.LastGeneration=max(obj.LastGeneration,obj.AsyncGeneration);
            end
            receipt=struct('status','OUTER_SUSPENDED_NO_PUBLICATION', ...
                'reason',string(reason),'now_ns',double(nowNs), ...
                'already_suspended',wasSuspended,'phase_s',obj.Adapter.phase_s, ...
                'inflight_retired',obj.AsyncInFlight,'last_generation',double(obj.LastGeneration), ...
                'command_committed',false,'hardware_actions',0);
        end

        function reference = stepReference(obj,dtS)
            assert(~obj.OuterSuspended,'gpenmpcNative:OuterLifecycleSuspended', ...
                'No reference progression during LAND/ground lifecycle.');
            assert(obj.ReferenceMode=="" ...
                || obj.ReferenceMode=="LEGACY_REFERENCE_ONLY", ...
                'gpenmpcNative:BoardReferenceModeConflict', ...
                'Legacy and current physical reference paths cannot be mixed.');
            obj.ReferenceMode="LEGACY_REFERENCE_ONLY";
            [obj.Adapter,reference] = gpenmpcNative.stepBoardReferenceAdapter( ...
                obj.Adapter,obj.Trajectory,dtS,obj.Config);
        end

        function receipt = beginLeg(obj,legIndex,trajectory,payloadKg, ...
                groundConfirmed,boardArmed,nowNs,px4Sample)
            % Reset per leg at the caller-controlled lifecycle boundary.
            % Failed sessions remain terminal.
            physical=obj.PhysicalRuntime.status();
            assert(~obj.Failed && ~obj.AsyncInFlight && ~physical.sample_open, ...
                'gpenmpcNative:BoardLegTransitionBusy', ...
                'Cannot reset failed, in-flight or uncommitted state.');
            assert(islogical(groundConfirmed)&&isscalar(groundConfirmed) ...
                &&groundConfirmed&&islogical(boardArmed)&&isscalar(boardArmed) ...
                &&~boardArmed&&isscalar(legIndex)&&isfinite(legIndex) ...
                &&legIndex==obj.CurrentLegIndex+1, ...
                'gpenmpcNative:BoardLegTransitionAuthority', ...
                'A sequential new leg requires confirmed ground and disarm.');
            % Validate/build locally before resetting any causal state.
            nextAdapter=gpenmpcNative.initializeBoardReferenceAdapter( ...
                obj.Config,trajectory,string(obj.Config.method));
            obj.PhysicalRuntime.prepareLegTransition(legIndex,payloadKg,nowNs,px4Sample);
            obj.Trajectory=trajectory;
            obj.Adapter=nextAdapter;
            obj.Adapter.last_committed_generation=obj.LastGeneration;
            obj.Adapter.publication_allowed=false;
            obj.WarmStart=zeros(1,obj.Config.decision_dimension);
            obj.CurrentLegIndex=double(legIndex);
            obj.CurrentPayloadKg=double(payloadKg);
            obj.FreshOuterForCurrentLeg=false;
            obj.OuterSuspended=false;
            obj.AsyncRetiredForLifecycle=false;
            obj.LegTransitionCount=obj.LegTransitionCount+uint64(1);
            receipt=struct('status','CANONICAL_NEW_LEG_RESET_NO_PUBLICATION', ...
                'leg_index',obj.CurrentLegIndex,'phase_s',0,'phase_rate',1, ...
                'warm_start_reset',true,'continuity_reset',true, ...
                'causal_history_reset',true,'outer_generation_preserved', ...
                double(obj.LastGeneration),'hardware_actions',0);
        end

        function response = stepGroundReference(obj,dtS,groundConfirmed,boardArmed)
            % Ground dwell belongs to delivery lifecycle, not flight phase.
            % No canonical outer/phase progress or command is consumed here.
            assert(obj.ReferenceMode=="CURRENT_A1_PHYSICAL", ...
                'gpenmpcNative:BoardGroundReferenceMode', ...
                'Ground lifecycle is available only on the physical path.');
            assert(islogical(groundConfirmed)&&isscalar(groundConfirmed) ...
                && groundConfirmed && islogical(boardArmed) ...
                && isscalar(boardArmed) && ~boardArmed, ...
                'gpenmpcNative:BoardGroundReferenceAuthority', ...
                'Ground clock advance requires confirmed ground and disarm.');
            assert(isscalar(dtS)&&isfinite(dtS)&&dtS>0, ...
                'gpenmpcNative:BoardGroundDt','Invalid dwell duration.');
            response=struct('schema', ...
                'GPENMPC_BOARD_GROUND_REFERENCE_RESPONSE_V1', ...
                'status','GROUND_DWELL_FLIGHT_CLOCK_PAUSED_NO_PUBLICATION', ...
                'phase_s',obj.Adapter.phase_s,'phase_rate',obj.Adapter.phase_rate, ...
                'dwell_step_s',double(dtS),'publication_allowed',false, ...
                'board_reference_publication_count',0, ...
                'hardware_actions',0,'com_open',0,'board_access',0);
        end

        function response = stepPhysicalReference(obj,generation,nowNs, ...
                px4Sample,runtime,dtS)
            assert(~obj.OuterSuspended,'gpenmpcNative:OuterLifecycleSuspended', ...
                'No control publication during LAND/ground lifecycle.');
            assert(~obj.Failed,'gpenmpcNative:BoardOuterFailed', ...
                'Board outer service is fail-closed: %s',obj.FailureCode);
            assert(obj.Prepared && obj.FreshOuterForCurrentLeg, ...
                'gpenmpcNative:BoardPhysicalReferenceNotAdmitted', ...
                'A fresh outer result is required before physical publication.');
            assert(obj.ReferenceMode=="" ...
                || obj.ReferenceMode=="CURRENT_A1_PHYSICAL", ...
                'gpenmpcNative:BoardReferenceModeConflict', ...
                'Legacy and current physical reference paths cannot be mixed.');
            obj.ReferenceMode="CURRENT_A1_PHYSICAL";
            % Read-only wall observations; NEVER supplied as control now/dt.
            profile=struct('scope','HOST_FUNCTION_OBSERVATION','clock_error','');
            profile=physicalProfileStamp(profile,'before_task_check_ns');
            obj.requireRuntimeTask(runtime);
            profile=physicalProfileStamp(profile,'before_adapter_ns');
            [obj.Adapter,baseReference] = ...
                gpenmpcNative.stepBoardReferenceAdapter( ...
                    obj.Adapter,obj.Trajectory,dtS,obj.Config);
            profile=physicalProfileStamp(profile,'after_adapter_ns');
            if ~baseReference.publication_allowed
                obj.Failed=true;
                obj.FailureCode="BASE_REFERENCE_PUBLICATION_SUPPRESSED";
                response=struct('schema', ...
                    'GPENMPC_BOARD_PHYSICAL_REFERENCE_RESPONSE_V1', ...
                    'accepted',false,'publication_allowed',false, ...
                    'reason',obj.FailureCode,'hardware_actions',0);
                return
            end
            profile=physicalProfileStamp(profile,'before_runtime_begin_ns');
            response=obj.PhysicalRuntime.beginSample( ...
                generation,nowNs,px4Sample,runtime, ...
                baseReference.reference_up,dtS);
            profile=physicalProfileStamp(profile,'after_runtime_begin_ns');
            response.schema= ...
                "GPENMPC_BOARD_PHYSICAL_REFERENCE_RESPONSE_V1";
            response.base_reference=baseReference;
            hostFullInner=isfield(response,'host_kernel_execution_allowed') ...
                &&isequal(response.host_kernel_execution_allowed,true) ...
                &&isfield(response,'board_publication_authority') ...
                &&isequal(response.board_publication_authority,false);
            boardPrepared=isfield(response,'board_commit_input_prepared') ...
                &&isequal(response.board_commit_input_prepared,true) ...
                &&isfield(response,'board_publication_authority')&&isequal(response.board_publication_authority,false);
            if ~response.accepted || (~response.publication_allowed && ~hostFullInner && ~boardPrepared)
                obj.Failed=true;
                obj.FailureCode="PHYSICAL_RUNTIME__"+string(response.reason);
                obj.Adapter.hard_invalid_latched=true;
                obj.Adapter.publication_allowed=false;
            end
            profile=physicalProfileStamp(profile,'after_response_ns');
            response.host_physical_profile=profile;
        end

        function response = commitPhysicalControl(obj,generation,nowNs,feedback)
            assert(obj.ReferenceMode=="CURRENT_A1_PHYSICAL", ...
                'gpenmpcNative:BoardPhysicalReferenceMode', ...
                'No current physical reference sample is open.');
