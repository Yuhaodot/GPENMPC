        function value = outerRuntime(obj,generation,nowNs,rotorCommandN, ...
                thrustEffectiveness,windEstimateXyMps,payloadKg)
            % Assemble the outer-solver input from causal runtime state and interface observations.
            assert(isfinite(generation)&&generation>=1 ...
                && generation==fix(generation) ...
                && isfinite(nowNs)&&nowNs>=0&&nowNs==fix(nowNs), ...
                'gpenmpcNative:BoardOuterRuntimeStamp','Invalid runtime stamp.');
            assert(isscalar(payloadKg)&&isfinite(payloadKg) ...
                &&payloadKg==obj.CurrentPayloadKg, ...
                'gpenmpcNative:CanonicalPayloadTransition', ...
                'Payload changes require the explicit ground-service leg transition.');
            rotor=double(rotorCommandN(:));
            effectiveness=double(thrustEffectiveness(:));
            wind=double(windEstimateXyMps(:));
            assert(numel(rotor)==6&&all(isfinite(rotor))&&all(rotor>=0) ...
                &&numel(effectiveness)==6&&all(isfinite(effectiveness)) ...
                &&all(effectiveness>0)&&numel(wind)==2&&all(isfinite(wind)) ...
                &&isfinite(payloadKg)&&payloadKg>=0, ...
                'gpenmpcNative:BoardOuterRuntimeValue','Invalid runtime value.');
            stamp=@(source)struct('source',source,'rx_ns',double(nowNs), ...
                'generation',double(generation),'valid',true);
            actuator=stamp('HOST_M600_VIRTUAL_ACTUATOR_INTERFACE');
            actuator.ordering='SOFTWARE_M600_ORDER';
            actuator.rotor_command_n=rotor;
            actuator.thrust_effectiveness=effectiveness;
            causal=obj.PhysicalRuntime.outerRuntimeState();
            if causal.desired_force_generation>0
                % After the first leg sample, use the previous controller command rather than lagged rotor state.
                actuator.rotor_command_n= ...
                    double(causal.previous_committed_rotor_command_n(:));
                actuator.command_source="PREVIOUS_COMMITTED_HIL_ACTUATOR_COMMAND";
                if causal.desired_force_source=="COMMITTED_CANONICAL_FULL_SE3_KERNEL_HOST_ONLY"
                    actuator.command_source="PREVIOUS_COMMITTED_FULL_KERNEL_HOST_COMMAND";
                elseif causal.desired_force_source=="COMMITTED_CANONICAL_FULL_SE3_KERNEL_BOARD_RFC1"
                    actuator.command_source="PREVIOUS_COMMITTED_FULL_KERNEL_BOARD_COMMAND";
                end
                actuator.command_generation=causal.desired_force_generation;
            else
                actuator.command_source="CANONICAL_LEG_INITIAL_ROTOR_STATE";
                actuator.command_generation=0;
            end
            if isempty(causal.previous_desired_force_projected_n)
                % Initialize the leg before its first control commit.
                causal.previous_desired_force_projected_n= ...
                    (double(obj.Assets.profile.mass_properties.base_mass_kg) ...
                    +double(payloadKg))*[0;0;9.80665];
                causal.desired_force_generation=0;
                causal.desired_force_source="CANONICAL_LEG_INITIAL_FORCE";
            end
            outer=stamp('HOST_CAUSAL_RUNTIME');
            names=fieldnames(causal);
            for k=1:numel(names),outer.(names{k})=causal.(names{k});end
            outer.previous_outer_acceleration_correction_i_mps2= ...
                double(obj.Adapter.previous_outer_correction_i_mps2(:));
            task=struct('source','FROZEN_GPENMPC_TASK_STATE', ...
                'payload_kg',double(payloadKg), ...
                'leg_index',obj.CurrentLegIndex, ...
                'corridor_half_width_m',double(obj.Config.corridor_half_width_m));
            windValue=stamp('FROZEN_TASK_WIND_ESTIMATOR');
            windValue.estimate_xy_mps=wind;
            value=struct('schema','GPENMPC_LIVE_OUTER_RUNTIME_V1', ...
                'task_identity_sha256',string(obj.Expected.task_identity_sha256), ...
                'plant_truth_used',false,'virtual_actuator',actuator, ...
                'outer',outer,'wind',windValue,'task',task);
        end

        function value = observedOuterRuntime(obj,generation,nowNs,virtualActuator,wind)
            % Live boundary: keep original external rx/generation. The
            % primitive outerRuntime API remains for isolated host fixtures
            % and the historical integrated-plant path, not sensor freshness.
            assert(~obj.Failed,'gpenmpcNative:BoardOuterFailed','Service is fail-closed.');
            fields={'rotor_thrust_state_n','thrust_effectiveness'};
            if ~isstruct(virtualActuator)||~all(isfield(virtualActuator,fields)) ...
                    ||~isstruct(wind)||~isfield(wind,'estimate_xy_mps')
                obj.Failed=true;obj.FailureCode="MISSING_OBSERVED_RUNTIME_INPUT";
                obj.Adapter.publication_allowed=false;
                error('gpenmpcNative:ObservedOuterRuntime','%s',obj.FailureCode);
            end
            prepared=obj.outerRuntime(generation,nowNs, ...
                virtualActuator.rotor_thrust_state_n,virtualActuator.thrust_effectiveness, ...
                wind.estimate_xy_mps,obj.CurrentPayloadKg);
            [value,ok,reason]=gpenmpcNative.bindCanonicalRuntimeObservations( ...
                prepared,virtualActuator,wind,nowNs,obj.Expected.maximum_runtime_age_ns);
            if ~ok
                obj.Failed=true;obj.FailureCode=reason;
                obj.Adapter.hard_invalid_latched=true;
                obj.Adapter.publication_allowed=false;
                error('gpenmpcNative:ObservedOuterRuntime','%s',reason);
            end
        end

