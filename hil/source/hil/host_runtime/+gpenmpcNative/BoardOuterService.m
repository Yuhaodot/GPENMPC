                obj.Failed=true;
                if isfield(response,'reason')
                    obj.FailureCode="PHYSICAL_CONTROL_COMMIT__" ...
                        +string(response.reason);
                else
                    obj.FailureCode="PHYSICAL_CONTROL_COMMIT_REJECTED";
                end
                obj.Adapter.hard_invalid_latched=true;
                obj.Adapter.publication_allowed=false;
            end
        end

