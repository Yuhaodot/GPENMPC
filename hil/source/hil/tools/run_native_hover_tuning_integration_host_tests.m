function report=run_native_hover_tuning_integration_host_tests(outputDir)
% Test orchestration with an in-memory adapter and synthetic clock and plant.
arguments
    outputDir (1,1) string
end
deviceFixture=gpenmpc_test_device_config(); %#ok<NASGU>
assert(~isfolder(outputDir)&&~isfile(outputDir),'m600check:TuningIntegrationOutputExists','Use a new HOST result directory.');
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'tools'),fullfile(root,'matlab_validation'), ...
    fullfile(root,'m600_coptersim','matlab_validation'));
[tuning,tv]=m600check.buildNativeHoverTuningContract();assert(tv.passed,'%s',tv.failure);
[geometry,gv]=m600check.buildTemporaryAllocatorGeometryContract( ...
    fullfile(gpenmpc_external_path('host_native_rotor_geometry'),'RESULT.json'));
assert(gv.passed,'%s',gv.failure);
checks=struct('name',{},'passed',{});cases=struct('name',{},'kind',{},'result',{},'exception',{});
runnerNames={'success','original_mismatch','partial_tuning','geometry_restore_failure', ...
    'tuning_restore_failure','applied_union_drift','partial_mapping','legacy_geometry_only'};
for caseIndex=1:numel(runnerNames)
    scenario=runnerNames{caseIndex};cfg=config(tuning,geometry);
    if strcmp(scenario,'legacy_geometry_only'),cfg=rmfield(cfg,'native_hover_tuning');end
    io=fixture(scenario,'RUNNER',tuning,geometry);r=[];problem='';
    try,r=run_m600_matlab_hil('',cfg,io);catch e,problem=[e.identifier ': ' e.message];end
    cases(end+1)=struct('name',scenario,'kind','REAL_RUNNER_INJECTED_MEMORY_IO','result',r,'exception',problem); %#ok<AGROW>
    check(['runner_' scenario '_returned'],isempty(problem)&&isstruct(r));
    if ~isempty(problem),continue;end
    check(['runner_' scenario '_closed_no_forbidden'],r.matlab_sockets_closed&& ...
        r.counts.force_disarm_requests==0&&r.counts.physical_output_actions==0&&r.counts.com_open_count==0);
    switch scenario
        case 'success'
            check('runner_success_full_hover_and_original138',r.formal_completed&&r.fresh_final_safe_state&& ...
                strcmp(r.status,'PASS_CALLER_DEFINED_M600_NATIVE_HOVER')&&r.native_hover_original138_restored);
            check('runner_success_all_three_union_reads',fullUnion(r.native_hover_parameter_union_original)&& ...
                fullUnion(r.native_hover_parameter_union_applied)&&fullUnion(r.native_hover_parameter_union_restored));
            check('runner_success_separate_apply_restore_counts', ...
                r.allocator_geometry_apply.ack_and_readback_verified_count==12&& ...
                r.allocator_geometry_restore.ack_and_readback_verified_count==12&& ...
                r.counts.tuning_apply_setter_attempts==3&&r.counts.tuning_apply_ack_readback_verified==3&& ...
                r.counts.tuning_restore_setter_attempts==3&&r.counts.tuning_restore_ack_readback_verified==3&& ...
                r.counts.mapping_verified_writes==6&&r.counts.mapping_verified_rollbacks==6);
            order=r.transport_evidence.mutations;kinds={order.kind};
            check('runner_success_actual_mutation_order', ...
                last(kinds,'GEOMETRY_APPLY')<first(kinds,'TUNING_APPLY')&& ...
                last(kinds,'TUNING_APPLY')<first(kinds,'MAPPING_APPLY')&& ...
                last(kinds,'MAPPING_RESTORE')<first(kinds,'GEOMETRY_RESTORE')&& ...
                last(kinds,'MAPPING_RESTORE')<first(kinds,'TUNING_RESTORE'));
            check('runner_original138_read_before_first_mutation', ...
                all(ismember({r.native_hover_parameter_union_original.rows.name},r.transport_evidence.reads_before_first_mutation)));
        case 'original_mismatch'
            check('runner_original_mismatch_zero_authority',contains(r.failure,'NativeHoverOriginal138')&& ...
                numel(r.native_hover_parameter_union_original.rows)==138&& ...
                ~r.native_hover_parameter_union_original.passed&&isempty(r.transport_evidence.mutations)&& ...
                r.counts.mapping_write_attempts==0&&r.counts.offboard_requests==0&&r.counts.arm_requests==0);
            check('runner_original_mismatch_not_safe_PASS',~r.native_hover_original138_restored&&~r.fresh_final_safe_state);
        case 'partial_tuning'
            check('runner_partial_tuning_real_attempt_retained',r.counts.tuning_apply_setter_attempts==2&& ...
                r.counts.tuning_apply_setter_returns==1&&r.counts.tuning_apply_ack_readback_verified==1&& ...
                contains(r.failure,'NativeHoverTuningApply'));
            check('runner_partial_tuning_both_restore_before_any_arm',r.allocator_geometry_restored&& ...
                r.native_hover_tuning_restored&&r.native_hover_original138_restored&& ...
                r.counts.tuning_restore_setter_attempts==2&&r.counts.tuning_restore_no_op==1&& ...
                r.counts.mapping_write_attempts==0&&r.counts.offboard_requests==0&&r.counts.arm_requests==0);
            check('runner_partial_failure_not_erased_by_safe_finally',r.fresh_final_safe_state&& ...
                ~isempty(r.failure)&&~startsWith(r.status,'PASS'));
        case 'geometry_restore_failure'
            check('runner_geometry_failure_does_not_skip_tuning',~r.allocator_geometry_restored&& ...
                r.native_hover_tuning_restored&&r.counts.tuning_restore_ack_readback_verified==3&& ...
                ~r.native_hover_original138_restored&&~r.fresh_final_safe_state&&~startsWith(r.status,'PASS'));
        case 'tuning_restore_failure'
            check('runner_tuning_failure_does_not_undo_geometry_receipt',r.allocator_geometry_restored&& ...
                ~r.native_hover_tuning_restored&&r.counts.tuning_restore_setter_attempts==3&& ...
                r.counts.tuning_restore_ack_readback_verified==2&&~r.fresh_final_safe_state&&~startsWith(r.status,'PASS'));
        case 'applied_union_drift'
            check('runner_applied138_rejects_unchanged_drift_before_mapping', ...
                contains(r.failure,'NativeHoverApplied138')&&numel(r.native_hover_parameter_union_applied.rows)==138&& ...
                r.counts.mapping_write_attempts==0&&r.counts.offboard_requests==0&&r.counts.arm_requests==0);
            check('runner_drift_not_blindly_overwritten',r.allocator_geometry_restored&&r.native_hover_tuning_restored&& ...
                ~r.native_hover_original138_restored&&strcmp(r.transport_evidence.drift_field_bits,'00000000'));
        case 'partial_mapping'
            check('runner_partial_mapping_zero_then_both_restore',contains(r.failure,'InjectedMapping')&& ...
                r.counts.mapping_write_attempts==3&&r.counts.mapping_verified_rollbacks==3&& ...
                r.allocator_geometry_restored&&r.native_hover_tuning_restored&&r.native_hover_original138_restored&& ...
                r.counts.arm_requests==0&&r.counts.offboard_requests==0);
        case 'legacy_geometry_only'
            check('legacy_twelve_geometry_API_unchanged',r.formal_completed&&r.fresh_final_safe_state&& ...
                r.allocator_geometry_apply.ack_and_readback_verified_count==12&& ...
                r.allocator_geometry_restore.ack_and_readback_verified_count==12&& ...
                isempty(r.native_hover_tuning_apply)&&isempty(r.native_hover_parameter_union_original)&& ...
                r.counts.tuning_apply_setter_attempts==0&&r.counts.mapping_verified_writes==6);
    end
end
recoveryNames={'success','partial_apply','already_original','geometry_restore_failure', ...
    'tuning_restore_failure','unknown_tuning','previous_owner_present','earlier_mapping_failure','emergency_force'};
for caseIndex=1:numel(recoveryNames)
    scenario=recoveryNames{caseIndex};cfg=config(tuning,geometry);
    cfg.independent_recovery_previous_owner_released=~strcmp(scenario,'previous_owner_present');
    cfg.allow_emergency_logical_force_disarm=strcmp(scenario,'emergency_force');
    io=fixture(scenario,'RECOVERY',tuning,geometry);r=[];problem='';
    try,r=recover_m600_canonical_udp(cfg,io);catch e,problem=[e.identifier ': ' e.message];end
    cases(end+1)=struct('name',scenario,'kind','REAL_RECOVERY_INJECTED_MEMORY_IO','result',r,'exception',problem); %#ok<AGROW>
    check(['recovery_' scenario '_returned'],isempty(problem)&&isstruct(r));
    if ~isempty(problem),continue;end
    check(['recovery_' scenario '_closed_no_physical_other_writes'],r.udp_closed&& ...
        r.counts.arm_requests==0&&r.counts.physical_mapping_writes==0&&r.counts.parameter_other_writes==0&& ...
        ~r.inner_result_reclassified&&~r.CopterSim_started_or_stopped);
    switch scenario
        case 'success'
            check('recovery_success_exact15_and138',r.safe_bridge_shutdown_allowed&&r.normal_termination_pass&& ...
                r.counts.geometry_restore_ack_readback_verified==12&&r.counts.tuning_restore_ack_readback_verified==3&& ...
                fullUnion(r.native_hover_parameter_union_restored));
            check('recovery_actual_finalread_guard_send_order',isequal(r.evidence.setter_steps, ...
                repmat({'FINAL_TYPED_READ';'FRESH_GUARD';'MOCK_PARAM_SET'},15,1)));
            check('recovery_unhealthy_model_does_not_block_safe_parameters',~r.final_snapshot.model_ready&& ...
                ~r.final_snapshot.clock_valid&&r.safe_bridge_shutdown_allowed);
        case 'partial_apply'
            check('recovery_partial_known_values_only',r.safe_bridge_shutdown_allowed&& ...
                r.counts.geometry_restore_setter_attempts==3&&r.counts.geometry_restore_no_op==9&& ...
                r.counts.tuning_restore_setter_attempts==2&&r.counts.tuning_restore_no_op==1);
        case 'already_original'
            check('recovery_noop_still_full_original_readback',r.safe_bridge_shutdown_allowed&& ...
                r.counts.geometry_restore_setter_attempts==0&&r.counts.tuning_restore_setter_attempts==0&& ...
                r.counts.geometry_restore_no_op==12&&r.counts.tuning_restore_no_op==3&& ...
                fullUnion(r.native_hover_parameter_union_restored));
        case 'geometry_restore_failure'
            check('recovery_geometry_failure_still_restores_tuning3',~r.geometry_original_identity_verified&& ...
                r.tuning_original_identity_verified&&r.counts.tuning_restore_ack_readback_verified==3&& ...
                ~r.safe_bridge_shutdown_allowed&&~r.normal_termination_pass);
        case 'tuning_restore_failure'
            check('recovery_tuning_failure_retains_geometry12_and_rejects_shutdown',r.geometry_original_identity_verified&& ...
                ~r.tuning_original_identity_verified&&r.counts.tuning_restore_setter_attempts==3&& ...
                r.counts.tuning_restore_ack_readback_verified==2&&~r.safe_bridge_shutdown_allowed&&~r.normal_termination_pass);
        case 'unknown_tuning'
            check('recovery_unknown_not_overwritten_known_remainder_restored',~r.safe_bridge_shutdown_allowed&& ...
                r.counts.tuning_restore_setter_attempts==2&&~r.tuning_restore_receipt.actions(1).attempted&& ...
                strcmp(r.evidence.first_tuning_bits,'3F800000')&&~r.normal_termination_pass);
        case 'previous_owner_present'
            check('recovery_previous_owner_required_for_both_services',r.counts.geometry_restore_setter_attempts==0&& ...
                r.counts.tuning_restore_setter_attempts==0&&contains(r.geometry_restore_failure,'PreviousOwnerNotReleased')&& ...
                contains(r.tuning_restore_failure,'PreviousOwnerNotReleased')&&~r.safe_bridge_shutdown_allowed);
        case 'earlier_mapping_failure'
            check('recovery_safe_identity_does_not_erase_original_mapping_failure',r.safe_bridge_shutdown_allowed&& ...
                r.native_hover_original138_restored&&contains(r.failure,'InjectedMapping')&&~r.normal_termination_pass);
        case 'emergency_force'
            check('recovery_force_must_not_become_normal_PASS',r.safe_bridge_shutdown_allowed&& ...
                r.counts.force_disarm_requests==1&&r.emergency_force_used&&~r.normal_termination_pass&& ...
                r.geometry_original_identity_verified&&r.tuning_original_identity_verified);
    end
end
% Test recovery validation independently of the launcher.
for caseIndex=1:2
    cfg=config(tuning,geometry);cfg.independent_recovery_previous_owner_released=true;
    io=fixture('success','RECOVERY',tuning,geometry);problem='';
    if caseIndex==1,cfg.native_hover_tuning.entries(1).target_raw_bits_hex='3F000000';label='bad_tuning';
    else,cfg.temporary_allocator_geometry.entries(1).original_raw_bits_hex='3F000000';label='bad_geometry_with_tuning';end
    try,recover_m600_canonical_udp(cfg,io);catch e,problem=[e.identifier ': ' e.message];end
    if caseIndex==1,expectedError='m600check:RecoveryTuningContract';
    else,expectedError='m600check:RecoveryTuningGeometryContract';end
    ev=io.evidence();check(['direct_recovery_' label '_rejected_before_IO'], ...
        contains(problem,expectedError)&&isempty(ev.commands)&&isempty(ev.mutations));
    cases(end+1)=struct('name',label,'kind','DIRECT_RECOVERY_PREFLIGHT_NEGATIVE', ...
        'result',ev,'exception',problem); %#ok<AGROW>
end
paths={fullfile(root,'tools','run_m600_matlab_hil.m'),fullfile(root,'tools','recover_m600_canonical_udp.m'), ...
    fullfile(root,'tools','launch_m600_canonical_hil.m'),fullfile(root,'tools','m600_canonical_serial_preflight.m')};
static=struct('path',{},'sha256',{},'checkcode',{},'scope',{});
for sourceIndex=1:numel(paths)
    static(end+1)=struct('path',paths{sourceIndex},'sha256',m600check.fileSha256(paths{sourceIndex}), ...
        'checkcode',checkcode(paths{sourceIndex},'-id'), ...
        'scope','STATIC_CODE_ANALYSIS'); %#ok<AGROW>
end
report=struct('schema','HOST_NATIVE_HOVER_TUNING_INTEGRATION_V1','passed',all([checks.passed]), ...
    'checks_total',numel(checks),'checks_passed',nnz([checks.passed]),'checks',checks,'cases',cases, ...
    'static_sources',static,'hardware_actions',0,'COM_UDP_actions',0,'flight_admission',false, ...
    'scope','Actual runner/recovery/helper memory-IO behavior; serial/launcher static only.', ...
    'limitations','Synthetic state and clock fixtures exercise tuning integration.');
mkdir(outputDir);save(fullfile(outputDir,'RESULT.mat'),'report','-v7.3');
fid=fopen(fullfile(outputDir,'RESULT.json'),'w','n','UTF-8');assert(fid>=0);c=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));clear c
fprintf('Tuning integration HOST: %d/%d\n',report.checks_passed,report.checks_total);
assert(report.passed,'m600check:TuningIntegratedHostFailed','Failed: %s',strjoin({checks(~[checks.passed]).name},', '));
    function check(name,value)
        checks(end+1)=struct('name',name,'passed',islogical(value)&&isscalar(value)&&value);
    end
end

function yes=fullUnion(r)
yes=isstruct(r)&&r.passed&&r.read_attempts==138&&numel(r.rows)==138&&all([r.rows.passed]);
end
function i=first(kinds,name),i=find(strcmp(kinds,name),1,'first');if isempty(i),i=Inf;end,end
function i=last(kinds,name),i=find(strcmp(kinds,name),1,'last');if isempty(i),i=-Inf;end,end
