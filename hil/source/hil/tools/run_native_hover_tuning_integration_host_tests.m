function io=fixture(scenario,kind,tuning,geometry)
params=containers.Map('KeyType','char','ValueType','any');
original=tuning.unchanged_guard_entries(:);
for seedIndex=1:3,e=tuning.entries(seedIndex);original(end+1)=struct('name',e.name,'mav_type',9,'raw_bits_hex',e.original_raw_bits_hex);end %#ok<AGROW>
for seedIndex=1:numel(original),e=original(seedIndex);params(e.name)=typed(e.name,e.mav_type,e.raw_bits_hex);end
for seedIndex=1:numel(tuning.output_guard_entries),e=tuning.output_guard_entries(seedIndex);params(e.name)=typed(e.name,e.mav_type,e.raw_bits_hex);end
allDelta=[geometry.entries(:);tuning.entries(:)];
if strcmp(kind,'RECOVERY')&&~strcmp(scenario,'already_original')
    for seedIndex=1:numel(allDelta)
        if strcmp(scenario,'partial_apply')&&~ismember(seedIndex,[1:3,13:14]),continue;end
        e=allDelta(seedIndex);params(e.name)=typed(e.name,9,e.target_raw_bits_hex);
    end
end
if any(strcmp(scenario,{'original_mismatch','applied_union_drift'}))
    assert(isKey(params,'FD_FAIL_R'));fdOriginal=params('FD_FAIL_R');assert(~strcmp(fdOriginal.raw_bits_hex,'00000000'));
end
if strcmp(scenario,'original_mismatch'),params('FD_FAIL_R')=typed('FD_FAIL_R',9,'00000000');end
if strcmp(scenario,'unknown_tuning'),e=tuning.entries(1);params(e.name)=typed(e.name,9,'3F800000');end
if strcmp(scenario,'earlier_mapping_failure'),params('HIL_ACT_FUNC1')=typed('HIL_ACT_FUNC1',6,'00000065');end
t=0;armed=0;landed=1;main=0;sub=0;pos=[0,0,-.25];target=pos;landAt=Inf;versionRx=-Inf;closed=false;
if strcmp(scenario,'emergency_force'),armed=1;landed=2;end
ack=[];reads={};beforeFirst={};steps=cell(0,1);commands=struct('command',{},'params',{},'time_s',{});
mutations=struct('kind',{},'name',{},'raw_bits_hex',{},'time_s',{});raw=struct('name',{}, ...
    'attempted',{},'send_returned',{},'ack_verified',{},'readback_verified',{});
version=struct('uid',uint64(3473490377)*uint64(1000000000)+uint64(90611257), ...
    'board_version',56,'flight_custom_version',uint8(1:8));
io=struct('now',@now,'sleep',@sleep,'snapshot',@snapshot,'sendHeartbeat',@noop, ...
    'sendSetpoint',@setpoint,'requestCommand',@command,'commandAck',@getAck,'readParameter',@readParam, ...
    'setIntegerParameter',@setInteger,'setRealParameter',@setGeometry, ...
    'setNativeHoverTuningParameter',@setTuning,'close',@closeIo,'evidence',@evidence);
    function x=now(),x=t;end
    function sleep(dt),t=t+dt;end
    function noop(),end
    function setpoint(p),target=p;if armed==1,pos=target;end,end
    function s=snapshot()
        if t>=landAt,pos=[0,0,-.25];landed=1;armed=0;end
        sample=struct('clock_id','MATLAB_MONOTONIC_MAPPED_SOURCE_TIME','time_s',t, ...
            'received_at_s',t,'position_ned_m',pos,'velocity_ned_mps',[0,0,0]);
        state=struct('raw_source_time_s',t,'rx_s',t,'position_ned_m',pos,'velocity_ned_mps',[0,0,0],'sample',sample);
        healthy=strcmp(kind,'RUNNER');d=struct('model_ready',healthy,'status','EXPLICIT_MEMORY_FIXTURE', ...
            'fatal_reason','','decoded',struct('ground_confirmed',landed==1));
        s=struct('now_s',t,'armed',armed,'landed_state',landed,'main_mode',main,'sub_mode',sub, ...
            'heartbeat_rx_s',t,'extended_rx_s',t,'estimate',state,'truth',state, ...
            'clock_valid',healthy,'model_ready',healthy,'model_diagnostic',d, ...
            'autopilot_version',version,'autopilot_version_rx_s',versionRx);
    end
    function command(cmd,p)
        t=t+.001;commands(end+1)=struct('command',cmd,'params',p,'time_s',t); %#ok<AGROW>
        if cmd==512,assert(p(1)==148);versionRx=t;
        elseif cmd==176&&p(2)==6,main=6;
        elseif cmd==176&&p(2)==4
            main=4;sub=6;if ~strcmp(scenario,'emergency_force'),landAt=t+.04;end
        elseif cmd==400&&p(1)==1,armed=1;landed=2;pos=target;
        elseif cmd==400&&p(1)==0,armed=0;if p(2)==21196,landed=1;end
        else,error('m600check:FixtureUnexpectedCommand','Unexpected fixture command.');end
        ack=struct('command',cmd,'result',0,'received_at_s',t);
    end
    function a=getAck(cmd,sent)
        a=[];if ~isempty(ack)&&ack.command==cmd&&ack.received_at_s>=sent,a=ack;end
    end
    function p=readParam(name)
        name=char(name);reads{end+1}=name;assert(isKey(params,name),'m600check:FixtureMissingTypedField','%s',name);p=params(name);
    end
    function p=setInteger(name,value)
        assert(startsWith(name,'HIL_ACT_FUNC')&&ismember(value,[0,101:106]));
        if isempty(mutations),beforeFirst=reads;end
        bits=upper(dec2hex(typecast(int32(value),'uint32'),8));
        if value==0,label='MAPPING_RESTORE';else,label='MAPPING_APPLY';end
        mutations(end+1)=struct('kind',label,'name',name,'raw_bits_hex',bits,'time_s',t); %#ok<AGROW>
        params(name)=typed(name,6,bits);
        if (strcmp(scenario,'partial_mapping')&&value==103)||strcmp(scenario,'earlier_mapping_failure')
            error('m600check:InjectedMapping','Mutation occurred before lost mapping ACK.');
        end
        p=readParam(name);
    end
    function p=setGeometry(name,bits,expectedBits,safeGuard)
        p=setReal(name,bits,expectedBits,safeGuard,'GEOMETRY',geometry.entries);
    end
    function p=setTuning(name,bits,expectedBits,safeGuard)
        p=setReal(name,bits,expectedBits,safeGuard,'TUNING',tuning.entries);
    end
    function p=setReal(name,bits,expectedBits,safeGuard,family,entries)
        e=entries(strcmp({entries.name},name));assert(isscalar(e));
        current=readParam(name);steps{end+1,1}='FINAL_TYPED_READ';
        assert(current.mav_type==9&&strcmpi(current.raw_bits_hex,expectedBits), ...
            'm600check:FixtureTOCTOUIdentity','Internal final read changed before send.');
        okay=safeGuard();steps{end+1,1}='FRESH_GUARD';
        assert(isequal(okay,true),'m600check:FixtureFreshGuard','Fresh state/output guard failed.');
        isApply=strcmpi(bits,e.target_raw_bits_hex);if isApply,suffix='APPLY';else,suffix='RESTORE';end
        % Send immediately after the final guard.
        steps{end+1,1}='MOCK_PARAM_SET';if isempty(mutations),beforeFirst=reads;end
        mutations(end+1)=struct('kind',[family '_' suffix],'name',name,'raw_bits_hex',bits,'time_s',t); %#ok<AGROW>
        raw(end+1)=struct('name',name,'attempted',true,'send_returned',false,'ack_verified',false,'readback_verified',false); %#ok<AGROW>
        blocked=(strcmp(scenario,'geometry_restore_failure')&&strcmp(family,'GEOMETRY')&&~isApply&&strcmp(name,geometry.entries(1).name))|| ...
            (strcmp(scenario,'tuning_restore_failure')&&strcmp(family,'TUNING')&&~isApply&&strcmp(name,tuning.entries(1).name));
        if blocked,error('m600check:InjectedRestore','Fixture restore send failed.');end
        params(name)=typed(name,9,bits);
        if strcmp(scenario,'partial_tuning')&&strcmp(family,'TUNING')&&isApply&&strcmp(name,tuning.entries(2).name)
            error('m600check:InjectedTuningACK','Mutation occurred but setter result was lost.');
        end
        if strcmp(scenario,'applied_union_drift')&&strcmp(family,'TUNING')&&isApply&&strcmp(name,tuning.entries(3).name)
            params('FD_FAIL_R')=typed('FD_FAIL_R',9,'00000000');
        end
        raw(end).send_returned=true;raw(end).ack_verified=true;raw(end).readback_verified=true;
        p=typed(name,9,bits);p.real_write_receipt=struct('attempted',true,'send_returned',true,'ack_verified',true,'readback_verified',true);
    end
    function yes=closeIo(),closed=true;yes=true;end
    function e=evidence()
        p=params(tuning.entries(1).name);d=params('FD_FAIL_R');
        e=struct('mock_only',true,'closed',closed,'commands',commands,'mutations',mutations, ...
            'real_parameter_actions',raw,'setter_steps',{steps},'reads_before_first_mutation',{beforeFirst}, ...
            'first_tuning_bits',p.raw_bits_hex,'drift_field_bits',d.raw_bits_hex);
    end
end
function p=typed(name,mavType,bits)
u=uint32(hex2dec(bits));if mavType==9,v=double(typecast(u,'single'));else,v=double(typecast(u,'int32'));end
p=struct('name',name,'mav_type',mavType,'decoded',v,'raw_bits_hex',upper(bits));
end
