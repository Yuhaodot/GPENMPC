function [wire,receipt]=sourcePwmSim(raw)
assert(isequal(size(raw),[6,1])&&all(isfinite(raw))&&all(raw>=0&raw<=1), ...
    'gpenmpc:BadAllocatorMotorValue');
% Match float rounding points in the THR_MDL_FAC=0 nonreversible branch.
u=single(raw);scaled=single(u.*single(2));motorFunction=single(scaled-single(1));
a=single(single(2000-1000)/single(1-(-1)));
b=single(single(1000)-single(a*single(-1)));
product=single(a.*motorFunction);interpolated=single(product+b);
interpolated(motorFunction<=single(-1))=single(1000);
interpolated(motorFunction>single(1))=single(2000);
% All values1000..2000 are positive. floor(double(float)+.5) is exactly
% C++ lroundf ties-away-from-zero on this declared domain, including .5.
rounded=floor(double(interpolated)+.5);pwm=uint16(min(max(rounded,0),65535));
scaledOutput=single(single(pwm)-single(1000));wireSingle=single(scaledOutput/single(1000));
wire=double(wireSingle);assert(all(wire>=0&wire<=1)&&all(isfinite(wire)));
receipt=struct('allocator_REAL32',u,'motor_function_minus1_to1_REAL32',motorFunction, ...
    'interpolated_pwm_REAL32',interpolated,'lroundf_integer',rounded,'pwm_uint16',pwm, ...
    'wire_REAL32',wireSingle,'thrust_factor',0,'motor_reversible',false,'idle_added',false);
end

