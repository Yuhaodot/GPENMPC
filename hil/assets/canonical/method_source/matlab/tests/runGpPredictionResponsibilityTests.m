function shadow = eligibleShadow()
shadow = struct( ...
    "available", true, ...
    "causal_valid", true, ...
    "observed_innovation_available", true, ...
    "gp_model_available", true, ...
    "hard_invalid", false, ...
    "trust", 0.8, ...
    "consistency_ewma_f", [0.8,0.8,0.8], ...
    "consistency_ewma_aggregate", 0.8, ...
    "observed_innovation_consistent", true);
end

function evidence = closedEvidence(observedF, predictedF)
evidence = eligibleShadow();
evidence.prediction_sample_closed = true;
evidence.observed_innovation_f_mps2 = observedF(:).';
evidence.predicted_mean_f_mps2 = predictedF(:).';
evidence.calibrated_half_width_f_mps2 = 0.1 .* ones(1,3);
end

function decision = decisionRecord(method, phase, correction)
decision = struct( ...
    "method", method, ...
    "success", true, ...
    "hard_invalid", false, ...
    "gp_b1_fallback_active", false, ...
    "fallback_reason", "", ...
    "phase_acceleration_s_inv", phase, ...
    "outer_acceleration_correction_f_mps2", correction, ...
    "mean_trust", 0.8, ...
    "elapsed_seconds", 0.01, ...
    "minimum_constraint_margin", 0.1);
end
