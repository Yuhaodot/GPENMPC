function testGpDoesNotCreateASecondPhysicalCandidate()
config = coreConfig();
warm = [0.01, -0.02, 0.03, -0.04, 0.02, -0.03, 0.04];
means = repmat([0.20, -0.10, 0.05], 8, 1);
b2 = gpenmpcBuildEnmpcCandidateLibrary(config.method, warm, means, config);
b1 = gpenmpcBuildEnmpcCandidateLibrary( ...
    config.b1_fallback_method, warm, zeros(0, 3), config);
assert(isequal(b2.values, b1.values));
assert(isequal(b2.labels, b1.labels));
assert(~b2.gp_candidate_inserted);
assert(b2.gp_mean_remains_in_rollout);
assert(b2.gp_prediction_only);
end

function testInnovationMismatchUsesContinuousWeightNotDiscreteFallback()
config = supervisorConfig();
state = gpenmpcInitializeOuterSupervisor(config);
shadow = eligibleShadow();
shadow.observed_innovation_consistent = false;
request = gpenmpcOuterSupervisorRequest(state, true, config, shadow);
assert(request.requested_method == config.method);
evidence = closedEvidence([0.0;0.0;0.0], [0.1;0.1;0.1]);
evidence.observed_innovation_consistent = false;
[weight, ~] = gpenmpcUpdateGpAgreementWeight( ...
    ones(3,1), evidence, 0.01, config);
assert(weight(1) < 1.0);
assert(all(weight < 1.0));
assert(all(weight > 0.0));
end

