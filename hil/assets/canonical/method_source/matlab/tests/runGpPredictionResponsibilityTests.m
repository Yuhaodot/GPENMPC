    @testInnovationMismatchUsesContinuousWeightNotDiscreteFallback, ...
    @testConsistentInnovationKeepsB2Active, ...
    @testMissingEvidenceFailsClosed, ...
    @testReentryProbeRequiresClosedEvidence, ...
    @testClosedEvidenceUsesFrozenSampleFrame, ...
    @testNominalInnovationWithholdsFalseGpAxis, ...
    @testMatchedInnovationCausallyEarnsGpAxis, ...
    @testActiveB2PreservesSolverEvaluatedTarget, ...
    @testSharedRotorCommandFeatureDefinition};
names = [ ...
    "GP_MEAN_REMAINS_PREDICTIVE_WITHOUT_DIRECT_CANCELLATION_CANDIDATE", ...
    "INNOVATION_MISMATCH_USES_CONTINUOUS_WEIGHT_NOT_DISCRETE_FALLBACK", ...
    "ACTIVE_CONSISTENT_INNOVATION_RETAINS_B2", ...
