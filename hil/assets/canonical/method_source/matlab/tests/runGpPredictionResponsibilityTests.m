    "REENTRY_PROBE_REQUIRES_CLOSED_EVIDENCE", ...
    "CLOSED_EVIDENCE_USES_ITS_FROZEN_SAMPLE_FRAME", ...
    "NOMINAL_INNOVATION_WITHHOLDS_FALSE_GP_AXIS", ...
