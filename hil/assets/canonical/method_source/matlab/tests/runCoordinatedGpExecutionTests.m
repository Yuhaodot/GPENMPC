function testFallbackAndReentryRespectCommonSlew()
[x, reference, robust, config, state] = fixture();
state.vertical_disturbance_ewma_mps2 = 0.2;
invalid = evidence([0.12;0.06;-0.08], eye(3), 0.9, true);
valid = evidence([0.12;0.06;-0.08], eye(3), 0.9, false);
previous = state.filtered_compensation_i_mps2;
[b1, state] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, invalid, ones(3,1), config);
assert(norm(b1 - previous) <= robust.compensation_slew_limit_mps3 .* 0.01 + 1e-12);
[active, state] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, valid, ones(3,1), config);
assert(norm(active - b1) <= robust.compensation_slew_limit_mps3 .* 0.01 + 1e-12);
[fallback, ~] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, invalid, ones(3,1), config);
assert(norm(fallback - active) <= robust.compensation_slew_limit_mps3 .* 0.01 + 1e-12);
end


