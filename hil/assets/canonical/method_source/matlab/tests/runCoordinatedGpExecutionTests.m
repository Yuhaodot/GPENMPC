function testHardInvalidAndZeroAuthorityAreExactB1()
[x, reference, robust, config, state] = fixture();
invalid = evidence([0.08;-0.04;0.12], eye(3), 0.8, true);
[expected, expectedState] = gpenmpcRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01);
[actual, actualState, diagnostic] = ...
    gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, invalid, ones(3,1), config);
assert(isequal(actual, expected));
assert(isequaln(actualState, expectedState));
assert(diagnostic.exact_b1_fallback);

valid = evidence([0.08;-0.04;0.12], eye(3), 0.8, false);
[actual, actualState] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, valid, zeros(3,1), config);
assert(isequal(actual, expected));
assert(isequaln(actualState, expectedState));
end


function testThreeAxisSignFrameUnitsAndSingleAuthority()
[x, reference, robust, config, state] = fixture();
theta = pi ./ 5.0;
frame = [cos(theta), -sin(theta), 0; sin(theta), cos(theta), 0; 0, 0, 1];
meanF = [0.12;-0.07;0.09];
trust = 0.8;
agreement = [1.0;0.75;0.5];
valid = evidence(meanF, frame, trust, false);
[augmentation, ~, diagnostic] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, valid, agreement, config);
expectedF = -(trust .* agreement .* meanF);
expectedI = frame * expectedF;
assert(max(abs(diagnostic.gp_execution_feedforward_i_mps2 - expectedI)) <= 1.0e-12);
assert(max(abs(frame.' * diagnostic.gp_execution_feedforward_i_mps2 ...
    - expectedF)) <= 1.0e-12);
assert(all(sign(frame.' * diagnostic.gp_execution_feedforward_i_mps2) ...
    == -sign(meanF)));
assert(norm(augmentation) <= robust.combined_compensation_cap_mps2 + 1.0e-12);
assert(norm(diagnostic.gp_execution_feedforward_i_mps2) ...
    <= robust.gp_compensation_cap_mps2 + 1.0e-12);
end


