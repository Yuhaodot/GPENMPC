function testPredictorPlantAndControlSignsMatch()
root = fileparts(fileparts(mfilename("fullpath")));
fixture = jsondecode(fileread(fullfile(root, "tests", "fixtures", ...
    "ordinary_b2_rollout_python_reference.json")));
stored = load(fullfile(root, "matlab", "native_training", ...
    "raw", "MATLAB_NATIVE_SPARSE_GP_MODEL.mat"), "nativeModel");
config = gpenmpcLoadOrdinaryB2Config(string(fixture.runtime_config_path));
config = gpenmpcApplyCoordinatedGpConfiguration(config);
trajectory = struct( ...
    "total_duration_s", double(fixture.trajectory.total_duration_s), ...
    "coefficients_ascending", double(fixture.trajectory.coefficients_ascending));
context = fixture.context;
context.phase_power_fcn = @fixedPower;
calibration = jsondecode(fileread(fullfile(root, "matlab", "simulink", ...
    "assets", "M600_DYN_CALIBRATION.json")));
allocation = gpenmpcM600Allocation(calibration);
context.rotor_allocation_pseudoinverse = allocation.pseudoinverse;
context.inertia_kg_m2 = allocation.inertia_kg_m2;
context.attitude_moment_gain_nm_per_rad = ...
    double(calibration.controller.attitude_moment_gain_nm_per_rad(:));
context.body_rate_moment_gain_nm_s_per_rad = ...
    double(calibration.controller.body_rate_moment_gain_nm_s_per_rad(:));
observation = fixture.observation;
observation.previous_rotor_command_n = repmat( ...
    norm(observation.previous_desired_force_n) ./ 6.0, 6, 1);
result = gpenmpcEvaluateOrdinaryB2Rollout( ...
    double(fixture.decision(:).'), config.method, trajectory, ...
    fixture.phase_state, observation, context, stored.nativeModel, ...
    fixture.causal_context_f17, config);
plant = vertcat(result.rows.predicted_gp_plant_residual_i_mps2);
control = vertcat(result.rows.predicted_gp_control_target_i_mps2);
assert(max(abs(plant + control), [], "all") <= 1.0e-12);
assert(all(isfinite(vertcat(result.rows.predicted_rotor_command_n)), "all"));
assert(result.control_activity_cost_signal == ...
    "PREDICTED_SIX_ROTOR_TOTAL_VARIATION");
end


function value = fixedPower(phase, airspeed, payload)
phaseDelta = 15.0 .* double(string(phase) == "ASCEND") ...
    + 8.0 .* double(string(phase) == "DESCEND");
value = 1050.0 + 9.0 .* airspeed.^2 + 20.0 .* payload + phaseDelta;
end


