function testPredictorRespectsRuntimeResponsibility()
root = fileparts(fileparts(mfilename("fullpath")));
fixtureData = jsondecode(fileread(fullfile(root, "tests", "fixtures", ...
    "ordinary_b2_rollout_python_reference.json")));
stored = load(fullfile(root, "matlab", "native_training", ...
    "raw", "MATLAB_NATIVE_SPARSE_GP_MODEL.mat"), "nativeModel");
config = gpenmpcLoadOrdinaryB2Config(string(fixtureData.runtime_config_path));
config = gpenmpcApplyResponsibilityConfiguration(config);
trajectory = struct( ...
    "total_duration_s", double(fixtureData.trajectory.total_duration_s), ...
    "coefficients_ascending", ...
        double(fixtureData.trajectory.coefficients_ascending));
context = fixtureData.context;
context.phase_power_fcn = @fixedPower;
calibration = jsondecode(fileread(fullfile(root, "matlab", "simulink", ...
    "assets", "M600_DYN_CALIBRATION.json")));
allocation = gpenmpcM600Allocation(calibration);
context.rotor_allocation_pseudoinverse = allocation.pseudoinverse;
context.inertia_kg_m2 = allocation.inertia_kg_m2;
context.attitude_moment_gain_nm_per_rad = ...
    double(calibration.controller.attitude_moment_gain_nm_per_rad(:));
context.body_rate_moment_gain_nm_s_per_rad = ...
    double(calibration.controller.body_rate_moment_gain_nm_s_per_rad(:));
observation = fixtureData.observation;
observation.previous_rotor_command_n = repmat( ...
    norm(observation.previous_desired_force_n) ./ 6.0, 6, 1);
causal = fixtureData.causal_context_f17;
causal.runtime_gp_responsibility_blend = 0.0;
causal.runtime_gp_filtered_mean_f_mps2 = zeros(3,1);
rollout = gpenmpcEvaluateOrdinaryB2Rollout( ...
    double(fixtureData.decision(:).'), config.method, trajectory, ...
    fixtureData.phase_state, observation, context, stored.nativeModel, ...
    causal, config);
plant = vertcat(rollout.rows.predicted_gp_plant_residual_i_mps2);
control = vertcat(rollout.rows.predicted_gp_control_target_i_mps2);
assert(max(abs(plant), [], "all") <= 1.0e-12);
assert(max(abs(control), [], "all") <= 1.0e-12);
end


