function testLowResidualStaysExactB1()
[x, reference, robust, config, candidateState] = fixture();
baselineState = candidateState;
sample = evidence([0.08;-0.04;0.12], [0.001;0.001;0.001], false);
for index = 1:200
    [expected, baselineState] = gpenmpcRobustSe3Augmentation( ...
        x, reference, robust, baselineState, 0.01);
    [actual, candidateState, diagnostic] = ...
        gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, candidateState, 0.01, sample, ones(3,1), config);
    assert(max(abs(actual - expected)) <= 1.0e-12);
    assert(diagnostic.gp_responsibility_blend == 0.0);
    assert(diagnostic.gp_authority == 0.0);
end
assert(~candidateState.gp_responsibility_mode_active);
end


function testHighResidualEntersAfterDwell()
[x, reference, robust, config, state] = fixture();
state.vertical_disturbance_ewma_mps2 = 0.20;
sample = evidence([0.12;-0.07;0.20], [0.10;0.08;0.25], false);
for index = 1:80
    [~, state, diagnostic] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, sample, ones(3,1), config);
end
assert(state.gp_responsibility_mode_active);
assert(abs(state.gp_responsibility_blend - 1.0) <= 1.0e-12);
assert(diagnostic.gp_authority > 0.0);
assert(isequal(diagnostic.vertical_observer_compensation_i_mps2, zeros(3,1)));
assert(abs(diagnostic.vertical_observer_shadow_i_mps2(3) + 0.20) <= 1.0e-12);
end


function testHysteresisPreventsChatter()
[x, reference, robust, config, state] = fixture();
high = evidence([0.12;-0.07;0.20], [0.10;0.08;0.25], false);
for index = 1:80
    [~, state] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, high, ones(3,1), config);
end
transitionCount = state.gp_responsibility_mode_transition_count;
middleInnovation = config.responsibility_residual_floor_f_mps2(:) .* 0.95;
middle = evidence([0.12;-0.07;0.20], middleInnovation, false);
for index = 1:120
    [~, state] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, middle, ones(3,1), config);
end
assert(state.gp_responsibility_mode_active);
assert(state.gp_responsibility_mode_transition_count == transitionCount);
end


function testCrossFadeIsComplementaryAndBounded()
[x, reference, robust, config, state] = fixture();
state.vertical_disturbance_ewma_mps2 = 0.20;
high = evidence([0.12;-0.07;0.20], [0.10;0.08;0.25], false);
previous = state.filtered_compensation_i_mps2;
foundTransition = false;
for index = 1:60
    [actual, state, diagnostic] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, high, ones(3,1), config);
    assert(norm(actual - previous) ...
        <= robust.compensation_slew_limit_mps3 .* 0.01 + 1.0e-12);
    previous = actual;
    blend = diagnostic.gp_responsibility_blend;
    if blend > 0.0 && blend < 1.0
        foundTransition = true;
        expectedObserver = (1.0 - blend) ...
            .* diagnostic.vertical_observer_shadow_i_mps2;
        assert(max(abs(diagnostic.vertical_observer_compensation_i_mps2 ...
            - expectedObserver)) <= 1.0e-12);
    end
end
assert(foundTransition);
end


function testHardInvalidImmediatelyReturnsB1()
[x, reference, robust, config, state] = fixture();
high = evidence([0.12;-0.07;0.20], [0.10;0.08;0.25], false);
for index = 1:80
    [~, state] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, high, ones(3,1), config);
end
invalid = high;
invalid.hard_invalid = true;
expectedState = state;
[expected, expectedState] = gpenmpcRobustSe3Augmentation( ...
    x, reference, robust, expectedState, 0.01);
[actual, actualState, diagnostic] = ...
    gpenmpcCoordinatedGpRobustSe3Augmentation( ...
    x, reference, robust, state, 0.01, invalid, ones(3,1), config);
assert(max(abs(actual - expected)) <= 1.0e-12);
assert(max(abs(actualState.filtered_compensation_i_mps2 ...
    - expectedState.filtered_compensation_i_mps2)) <= 1.0e-12);
assert(diagnostic.exact_b1_fallback);
assert(actualState.gp_responsibility_blend == 0.0);
end


function testGpMeanFilterIsCausalAndBandwidthLimited()
[x, reference, robust, config, state] = fixture();
high = evidence([0.30;-0.20;0.25], [0.10;0.08;0.25], false);
entered = false;
for index = 1:100
    [~, state, diagnostic] = gpenmpcCoordinatedGpRobustSe3Augmentation( ...
        x, reference, robust, state, 0.01, high, ones(3,1), config);
    if diagnostic.gp_responsibility_blend > 0.0
        entered = true;
        break
    end
end
assert(entered);
assert(norm(diagnostic.gp_filtered_control_target_i_mps2) ...
    < norm(diagnostic.gp_raw_control_target_i_mps2));
end


